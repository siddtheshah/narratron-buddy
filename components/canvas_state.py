    def get_doodle_snapshot_png(self) -> Optional[bytes]:
        """Render the current image with normalized doodle strokes as a PNG."""
        if not self.shown_image_path or not self.doodles_state:
            return None
        try:
            from PIL import Image, ImageDraw

            with Image.open(self.shown_image_path) as source:
                image = source.convert("RGBA")
            image.thumbnail((1600, 1600))
            draw = ImageDraw.Draw(image)
            width, height = image.size
            scale = max(1.0, min(width, height) / 900)
            for action in self.doodles_state:
                if action.get("type") != "draw":
                    continue
                try:
                    points = (float(action["x0"]) * width, float(action["y0"]) * height,
                              float(action["x1"]) * width, float(action["y1"]) * height)
                    draw.line(points, fill=action.get("color", "#ffffff"),
                              width=max(1, round(float(action.get("size", 3)) * scale)))
                except (KeyError, TypeError, ValueError):
                    continue
            output = io.BytesIO()
            # This image is an ephemeral agent-observability payload. Favor
            # quick encoding over expensive PNG optimization.
            image.convert("RGB").save(output, format="PNG", compress_level=1)
            return output.getvalue()
        except Exception as exc:
            logger.warning("Failed to render viewer doodle snapshot: %s", exc)
            return None

    def set_tool_activity(
        self, tool: str, active: bool = True, recent_seconds: float = 5.0,
        result: Optional[Dict[str, Any]] = None,
    ):
        """Update transient canvas indicators for agent tool use."""
        if tool == "image":
            self.image_generation_active = bool(active)
        elif tool == "live":
            self.live_connection_active = bool(active)
            if active and recent_seconds > 0:
                self.live_connection_until = time.time() + max(0.0, recent_seconds)
            elif not active:
                self.live_connection_until = 0.0
        elif tool == "dice":
            self.dice_roll_until = (
                time.time() + max(0.0, recent_seconds)
                if active and recent_seconds > 0
                else 0.0
            )
            self.dice_roll_result = dict(result) if active and result else None
        self._notify_state_changed("latest")

    def get_tool_activity(self) -> Dict[str, bool]:
        now = time.time()
        dice_rolling = now < self.dice_roll_until
        return {
            "image_generating": self.image_generation_active,
            "live_ready": self.live_connection_active or (now < self.live_connection_until),
            "dice_rolling": dice_rolling,
            "dice_result": self.dice_roll_result if dice_rolling else None,
        }

