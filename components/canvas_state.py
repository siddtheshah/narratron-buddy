    def _resolve_adventure_cover(self) -> Optional[Tuple[Path, str]]:
        """Look up adventure cover image from metadata.json if present."""
        if not self.theater_id:
            return None
        theater_dir = self.theater.directory()
        theater_ref_dir = self.theater.references_dir()
        metadata_file = theater_dir / "metadata.json"
        if not metadata_file.exists():
            return None

        try:
            import json
            meta = json.loads(metadata_file.read_text(encoding="utf-8"))
        except Exception as e:
            logger.warning(f"Failed to read metadata.json for theater {self.theater_id}: {e}")
            return None

        cover_image_setting = meta.get("cover_image")
        cover_file = None
        if cover_image_setting:
            clean_cover = cover_image_setting
            for prefix in ("references/", "reference_library/"):
                if clean_cover.startswith(prefix):
                    clean_cover = clean_cover[len(prefix):]

            candidates = [
                theater_ref_dir / cover_image_setting,
                theater_dir / cover_image_setting,
                theater_ref_dir / clean_cover,
                theater_dir / clean_cover,
                theater_ref_dir / Path(cover_image_setting).name,
            ]
            for cand in candidates:
                if cand.exists() and cand.is_file():
                    cover_file = cand
                    break

            if not cover_file and theater_ref_dir.exists():
                match_name = Path(cover_image_setting).name.lower()
                for f in theater_ref_dir.rglob("*"):
                    if f.is_file() and f.name.lower() == match_name:
                        cover_file = f
                        break

        if cover_file:
            title = meta.get("title")
            prompt = extract_image_prompt(str(cover_file)) or (f"Adventure Cover: {title}" if title else f"Mounted Reference: {cover_file.stem}")
            return cover_file, prompt
        return None

    def _resolve_reference_fallback(self) -> Optional[Tuple[Path, str]]:
        """Fallback to first reference image (prioritizing cover-named images)."""
        if not self.theater_id:
            return None
        theater_ref_dir = self.theater.references_dir()
        if not theater_ref_dir.exists():
            return None
        ref_images = [f for f in theater_ref_dir.iterdir() if f.is_file() and f.suffix.lower() in (".png", ".jpg", ".jpeg", ".webp")]
        if not ref_images:
            return None
        cover_candidates = [f for f in ref_images if "cover" in f.stem.lower()]
        chosen = cover_candidates[0] if cover_candidates else ref_images[0]
        prompt = extract_image_prompt(str(chosen)) or f"Mounted Reference: {chosen.stem}"
        return chosen, prompt

    def _resolve_active_image(self) -> Tuple[Optional[str], Optional[str], float, str]:
        """Resolve current displayed image: explicit shown image, newest artifact, adventure cover, or mounted reference.

        Returns:
            Tuple of (image_url, file_path_str, timestamp, prompt_text)
        """
        # 1. Explicit shown image
        if self.shown_image_path:
            return self._get_url_for_path(self.shown_image_path), self.shown_image_path, self.shown_image_time, self.shown_image_prompt

        # 2. Output directory latest generated image
        image_folder = str(self.theater.output_dir())
        if os.path.exists(image_folder):
            files = []
            for ext in ("*.png", "*.jpg", "*.jpeg", "*.webp"):
                files.extend(glob.glob(os.path.join(image_folder, ext)))
            if files:
                newest = max(files, key=os.path.getmtime)
                return self._get_url_for_path(newest), newest, os.path.getmtime(newest), extract_image_prompt(newest)

        # 3. Adventure cover from metadata.json
        cover = self._resolve_adventure_cover()
        if cover:
            cover_path, prompt = cover
            return self._get_url_for_path(str(cover_path)), str(cover_path), 0.0, prompt

        # 4. Mounted reference fallback
        ref = self._resolve_reference_fallback()
        if ref:
            ref_path, prompt = ref
            return self._get_url_for_path(str(ref_path)), str(ref_path), 0.0, prompt

        return None, None, 0.0, ""

    def get_latest_state(self) -> Dict[str, Any]:
        music_state = self._get_music_state()
        image_url, selected_file, selected_time, prompt_text = self._resolve_active_image()

        if selected_file:
            self.current_image_basename = os.path.basename(selected_file)

        transition = getattr(self, "shown_image_transition", "fade") or "fade"
        effect = getattr(self, "shown_image_effect", "gleam3") or "gleam3"

        formatted_history = []
        for h in self.shown_images_history:
            if isinstance(h, dict):
                formatted_history.append(h)
            elif isinstance(h, str):
                formatted_history.append({
                    "path": h,
                    "url": self._get_url_for_path(h),
                    "prompt": extract_image_prompt(h),
                    "time": 0.0,
                    "transition": transition,
                    "effect": effect,
                })

        if selected_file and not self.shown_images_history:
            item = {
                "path": selected_file,
                "url": image_url,
                "prompt": prompt_text,
                "time": selected_time,
                "transition": transition,
                "effect": effect,
            }
            self.shown_images_history.append(item)
            formatted_history.append(item)

        res = {
            "latest": image_url,
            "time": selected_time,
            "prompt": prompt_text,
            "music": music_state,
            "doodles_enabled": self.doodles_enabled,
            "viewer_collab_enabled": self.viewer_collab_enabled,
            "transition": transition,
            "effect": effect,
            "history": formatted_history,
            "tool_activity": self.get_tool_activity(),
            "agent_thought": self.get_agent_thought(),
            "scene_dialogue": list(self.scene_dialogue),
            "narration": self.narration,
            "character_voice_assignments": dict(self.character_voice_assignments),
            "sticky_notes": self.get_sticky_notes(),
            "interactive_surfaces": list(self.interactive_surfaces.values()),
        }
        if self.shown_animation_frames:
            res["animation"] = {
                "type": "triframe",
                "frames": [self._get_url_for_path(path) for path in self.shown_animation_frames],
                "frame_duration_ms": 1400,
                "crossfade_duration_ms": 500,
            }
        logger.debug(f"[/api/latest] returning latest={res['latest']}, time={res['time']}, history_len={len(formatted_history)}, playlist={music_state['playlist']}")
        return res

    def export_theater_data(self, theater_dir: Optional[Path] = None) -> tuple[Dict[str, Any], List[Dict[str, Any]]]:
        """Ensure current displayed image is saved and gather theater metadata, canvas data and files."""
        import json
        if self.shown_image_path and theater_dir:
            self.update_shown_image(
                self.shown_image_path,
                theater_id=theater_dir.name,
                transition=getattr(self, "shown_image_transition", "fade"),
                effect=getattr(self, "shown_image_effect", "gleam3"),
                clear_animation=False,
            )

        canvas_state = {
            "current_image_basename": self.current_image_basename,
            "shown_image_path": self.shown_image_path,
            "shown_image_prompt": self.shown_image_prompt,
            "shown_images_history": self.shown_images_history,
            "shown_image_transition": getattr(self, "shown_image_transition", "fade"),
            "shown_image_effect": getattr(self, "shown_image_effect", "gleam3"),
            "shown_animation_frames": list(self.shown_animation_frames),
            "current_playlist": self.current_playlist,
            "current_playlist_tracks": self.current_playlist_tracks,
            "music_paused": self.music_paused,
            "doodles": list(self.doodles_state),
            "doodles_enabled": self.doodles_enabled,
            "viewer_collab_enabled": self.viewer_collab_enabled,
            "named_elements": list(self.named_elements),
            "story_planning_state": dict(self.story_planning_state) if isinstance(self.story_planning_state, dict) else {},
            "scene_dialogue": list(self.scene_dialogue),
            "narration": self.narration,
            "interactive_surfaces": list(self.interactive_surfaces.values()),
            "character_voice_assignments": dict(self.character_voice_assignments),
            "suggestions": self.chat_manager.export_suggestions(),
            "chat_messages": self.chat_manager.get_messages(),
        }

        metadata = {}
        if theater_dir:
            theater_dir = Path(theater_dir).resolve()
            theater_dir.mkdir(parents=True, exist_ok=True)
            meta_file = theater_dir / "theater.json"
            if meta_file.exists():
                try:
                    with open(meta_file, "r", encoding="utf-8") as f:
                        metadata = json.load(f)
                except Exception:
                    metadata = {}

            # A canvas update can be the first write after a restored
            # deployment.  Always retain the minimum TheaterMetadata identity
            # fields so later agent initialization can read theater.json.
            metadata.setdefault("theater_id", self.theater_id)
            metadata.setdefault("name", self.theater_id)
            metadata["canvas_state"] = canvas_state

            try:
                with open(meta_file, "w", encoding="utf-8") as f:
                    json.dump(metadata, f, indent=2)
            except Exception as e:
                logger.warning(f"Failed to update theater.json: {e}")

            # Remove legacy theater_state.json if it exists
            legacy_file = theater_dir / "theater_state.json"
            if legacy_file.exists():
                try:
                    legacy_file.unlink()
                except Exception:
                    pass

        state_data = dict(metadata)
        if "canvas_state" not in state_data:
            state_data["canvas_state"] = canvas_state

        image_files = []
        seen_filenames = set()
        if theater_dir and theater_dir.exists():
            for f in theater_dir.rglob("*"):
                if f.is_file() and f.name not in ["theater.json", "theater_state.json"]:
                    rel_path = str(f.relative_to(theater_dir)).replace("\\", "/")
                    if rel_path not in seen_filenames:
                        seen_filenames.add(rel_path)
                        if "references" in f.parts:
                            category = "reference"
                        elif "output" in f.parts:
                            category = "output"
                        else:
                            category = str(f.parent.relative_to(theater_dir)).replace("\\", "/")

                        try:
                            with open(f, "rb") as fp:
                                image_files.append({
                                    "filename": f.name,
                                    "category": category,
                                    "data": fp.read()
                                })
                        except Exception:
                            pass

        return state_data, image_files
